-- Q34. Using a CTE, find ships whose combined total distance
-- covered by all sailors is greater than 2000 nautical miles.
WITH ShipDistance AS (
    SELECT s.ship_id,
           SUM(v.distance_covered_nm) AS total_distance
    FROM Sailors s
    JOIN VoyageLogs v
        ON s.sailor_id = v.sailor_id
    GROUP BY s.ship_id
)
SELECT sh.ship_name,
       sd.total_distance
FROM Ships sh
JOIN ShipDistance sd
    ON sh.ship_id = sd.ship_id
WHERE sd.total_distance > 2000;


-- Q35. Using a CTE, find each sailor's name and average hours on duty,
-- along with the ship type they work on.
WITH AvgHours AS (
    SELECT sailor_id,
           AVG(hours_on_duty) AS avg_hours
    FROM VoyageLogs
    GROUP BY sailor_id
)
SELECT s.sailor_name,
       ah.avg_hours,
       sh.ship_type
FROM Sailors s
JOIN Ships sh
    ON s.ship_id = sh.ship_id
JOIN AvgHours ah
    ON s.sailor_id = ah.sailor_id;


-- Q36. Using a CTE, find each ship's name and the number of voyage
-- logs recorded by sailors on that ship.
WITH ShipLogs AS (
    SELECT s.ship_id,
           COUNT(v.log_id) AS total_logs
    FROM Sailors s
    JOIN VoyageLogs v
        ON s.sailor_id = v.sailor_id
    GROUP BY s.ship_id
)
SELECT sh.ship_name,
       sl.total_logs
FROM Ships sh
JOIN ShipLogs sl
    ON sh.ship_id = sl.ship_id;


-- Q37. Using a CTE, find sailors whose total distance covered
-- is above the average total distance across all sailors.
WITH SailorDistance AS (
    SELECT sailor_id,
           SUM(distance_covered_nm) AS total_distance
    FROM VoyageLogs
    GROUP BY sailor_id
),
AverageDistance AS (
    SELECT AVG(total_distance) AS avg_total_distance
    FROM SailorDistance
)
SELECT s.sailor_name,
       sh.ship_name,
       sd.total_distance
FROM Sailors s
JOIN Ships sh
    ON s.ship_id = sh.ship_id
JOIN SailorDistance sd
    ON s.sailor_id = sd.sailor_id
CROSS JOIN AverageDistance ad
WHERE sd.total_distance > ad.avg_total_distance;


-- Q38. Using a CTE, find each rank along with the total cargo
-- handled by sailors of that rank.
WITH RankCargo AS (
    SELECT s.rank_name,
           SUM(v.cargo_handled_tons) AS total_cargo
    FROM Sailors s
    JOIN VoyageLogs v
        ON s.sailor_id = v.sailor_id
    GROUP BY s.rank_name
)
SELECT *
FROM RankCargo;


-- Q39. Using a CTE, find each ship's name and its youngest sailor's age.
WITH YoungestSailor AS (
    SELECT ship_id,
           MIN(age) AS youngest_age
    FROM Sailors
    GROUP BY ship_id
)
SELECT sh.ship_name,
       ys.youngest_age
FROM Ships sh
JOIN YoungestSailor ys
    ON sh.ship_id = ys.ship_id;


