-- Q32. Using a CTE, find each ship's name along with
-- the total cargo handled by all its sailors combined.
WITH ShipCargo AS (
    SELECT s.ship_id,
           SUM(v.cargo_handled_tons) AS total_cargo
    FROM Sailors s
    JOIN VoyageLogs v
        ON s.sailor_id = v.sailor_id
    GROUP BY s.ship_id
)
SELECT sh.ship_name,
       sc.total_cargo
FROM Ships sh
JOIN ShipCargo sc
    ON sh.ship_id = sc.ship_id;


-- Q33. Using a CTE, find each sailor's name, rank,
